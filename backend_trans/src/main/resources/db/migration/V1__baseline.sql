-- === alerte ===

create table alertes (
    id uuid not null,
    equipement_id uuid not null,
    type_anomalie varchar(30) not null
        check (type_anomalie in ('INDISPONIBILITE', 'CPU', 'RAM', 'DISQUE', 'RESEAU', 'MATERIEL')),
    severite varchar(20) not null
        check (severite in ('INFO', 'AVERTISSEMENT', 'CRITIQUE')),
    statut varchar(20) not null
        check (statut in ('DECLENCHEE', 'PRISE_EN_COMPTE', 'RESOLUE')),
    date_declenchement timestamp(6) not null,
    date_resolution timestamp(6),
    dernier_rappel timestamp(6),
    utilisateur_prise_en_charge bigint,
    primary key (id)
);

-- === audit ===

create table journal_audit (
    id bigint generated by default as identity,
    utilisateur_id bigint not null,
    action varchar(255) not null,
    horodatage timestamp(6) not null,
    adresse_ip_source varchar(45),
    primary key (id)
);

-- === rapport ===

create table rapports (
    id uuid not null,
    type_rapport varchar(20) not null
        check (type_rapport in ('JOURNALIER', 'HEBDOMADAIRE', 'MENSUEL')),
    periode_debut timestamp(6) not null,
    periode_fin timestamp(6) not null,
    chemin_fichier_pdf varchar(255),
    date_generation timestamp(6) not null,
    primary key (id)
);

-- === index ===

create index idx_alerte_statut on alertes (statut);
create index idx_metrique_equipement_horodatage on metriques (equipement_id, horodatage);
create index idx_metrique_horaire_equipement on metriques_horaires (equipement_id, heure);
create index idx_metrique_journaliere_equipement on metriques_journalieres (equipement_id, jour);

