-- Baseline Flyway (issue #139) : capture du schema PostgreSQL actuel tel que
-- produit jusqu'ici par Hibernate (spring.jpa.hibernate.ddl-auto=update), pour
-- les 11 entites JPA existantes (7 modules : auth, equipement, alerte, seuil,
-- metrique, audit, rapport). A partir de cette version, le schema n'evolue
-- plus que par migrations Flyway versionnees (V2, V3, ...) ; ddl-auto passe a
-- "validate".
--
-- Genere par bootstrap Hibernate pur (MetadataSources + SchemaManagementTool,
-- sans connexion a une base reelle : pas de Postgres accessible dans
-- l'environnement d'edition) a partir du mapping JPA actuel des entites,
-- verifie manuellement contre chaque @Table/@Column/@JoinColumn. NE COUVRE
-- PAS TimescaleDB (hypertable/continuous aggregates/retention sur
-- "metriques") : cf. issue #56, non implementee a ce jour malgre son etat
-- "closed" sur GitHub (cf. commentaires de suivi sur #56 et #57) - cette
-- baseline reste donc du PostgreSQL standard, sans extension. Le passage a
-- TimescaleDB, une fois #56 reellement traite, se fera via une migration
-- ulterieure (Vn__timescaledb.sql) qui convertira "metriques" en hypertable.

-- === auth ===

create table app_users (
    id bigint generated by default as identity,
    username varchar(255) not null,
    email varchar(255) not null unique,
    password_hash varchar(255) not null,
    role varchar(255) not null
        check (role in ('ADMINISTRATEUR', 'TECHNICIEN', 'OBSERVATEUR')),
    user_type varchar(255) not null
        check (user_type in ('INDIVIDUAL', 'BUSINESS', 'PARTNER')),
    active boolean not null,
    notifications_email boolean not null default true,
    failed_login_attempts integer not null,
    locked_until timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table refresh_tokens (
    id uuid not null,
    token varchar(255) not null unique,
    app_user_id bigint not null,
    expiry_date timestamp(6) not null,
    revoked boolean not null,
    created_at timestamp(6) not null,
    primary key (id)
);

create table password_reset_tokens (
    id uuid not null,
    token varchar(255) not null unique,
    app_user_id bigint not null,
    expiry_date timestamp(6) not null,
    used boolean not null,
    created_at timestamp(6) not null,
    primary key (id)
);

-- === equipement ===

create table equipements (
    id uuid not null,
    nom varchar(150) not null,
    adresse_ip varchar(45) not null unique,
    type varchar(30) not null
        check (type in ('SERVEUR', 'ROUTEUR', 'SWITCH', 'POINT_ACCES')),
    localisation varchar(150),
    etat varchar(30) not null
        check (etat in ('ACTIF', 'INACTIF', 'EN_MAINTENANCE')),
    description text,
    cle_api varchar(255),
    depend_de_id uuid,
    derniere_mesure timestamp(6),
    primary key (id)
);

